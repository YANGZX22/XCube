// Usage: node tools/vendor-material-icons.cjs /path/to/material-icon-theme/package
// Input: the unpacked, integrity-verified material-icon-theme@5.38.1 npm archive.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const packageDir = path.resolve(process.argv[2] || '');
const pkg = JSON.parse(fs.readFileSync(path.join(packageDir, 'package.json'), 'utf8'));
assert.equal(pkg.name, 'material-icon-theme');
assert.equal(pkg.version, '5.38.1');
assert.equal(pkg.license, 'MIT');
const manifest = require(packageDir).generateManifest();
function normalizeKeys(entries) {
  return Object.fromEntries(Object.entries(entries).map(([key, value]) => [key.toLowerCase(), value]));
}
const names = { ...normalizeKeys(manifest.fileNames), 'oh-package.json5': 'json', 'oh-package-lock.json5': 'json' };
const extensions = { ...normalizeKeys(manifest.fileExtensions), ets: 'typescript', hap: 'zip', hsp: 'zip' };
const variants = {};
for (const group of ['fileNames', 'fileExtensions', 'languageIds']) {
  for (const [key, lightIcon] of Object.entries(manifest.light[group] || {})) {
    const darkIcon = manifest[group][key];
    assert.ok(darkIcon, `Missing base mapping: ${group}/${key}`);
    assert.ok(!variants[darkIcon] || variants[darkIcon] === lightIcon, `Conflicting light icon: ${darkIcon}`);
    variants[darkIcon] = lightIcon;
  }
}
const fallbackIcons = ['file', 'document', 'image', 'audio', 'video', 'zip', 'font', 'pdf',
  'word', 'table', 'powerpoint', 'json', 'xml', 'readme', 'docker', 'tune'];
const used = new Set([...Object.values(names), ...Object.values(extensions),
  ...Object.keys(variants), ...Object.values(variants), ...fallbackIcons]);
const output = path.join(root, 'entry/src/main/resources/rawfile/file-icons/material');
fs.mkdirSync(output, { recursive: true });
const hashes = {};
let totalBytes = 0;
for (const id of [...used].sort()) {
  assert.match(id, /^[a-z0-9_-]+$/i);
  const definition = manifest.iconDefinitions[id];
  assert.ok(definition, `Missing definition: ${id}`);
  const name = path.basename(definition.iconPath);
  assert.ok(name === `${id}.svg` || name === `${id}.clone.svg`, `Unexpected SVG path: ${name}`);
  const source = path.join(packageDir, 'icons', name);
  const svg = fs.readFileSync(source);
  assert.match(svg.toString(), /<svg\b/);
  assert.doesNotMatch(svg.toString(), /<(?:script|foreignObject|image)\b|(?:href|src)\s*=\s*["'](?!#)/i);
  fs.writeFileSync(path.join(output, `${id}.svg`), svg);
  hashes[`${id}.svg`] = crypto.createHash('sha256').update(svg).digest('hex');
  totalBytes += svg.length;
}
fs.copyFileSync(path.join(packageDir, 'LICENSE'), path.join(output, 'LICENSE.txt'));
fs.writeFileSync(path.join(output, 'SOURCE.json'), JSON.stringify({
  name: pkg.name,
  version: pkg.version,
  license: pkg.license,
  repository: 'https://github.com/material-extensions/vscode-material-icon-theme',
  archive: 'https://registry.npmjs.org/material-icon-theme/-/material-icon-theme-5.38.1.tgz',
  archiveIntegrity: 'sha512-14cFM4NJGdbuo68rIZTq9TSX0f5BtA6VF+eNX3zq23Z5NoEeVtM4Zn4PpZ0ERl++50jCBrywKFWXmOjbxf0xTA==',
  modifications: 'SVG artwork is unmodified; upstream .clone.svg filenames are normalized to <icon-id>.svg. Generated file associations add ArkTS (.ets) and HarmonyOS package files (.hap, .hsp, oh-package*.json5). Folder icons are not bundled.',
  iconCount: used.size,
  svgBytes: totalBytes,
  sha256: hashes
}, null, 2) + '\n');
function table(name, entries) {
  return `export const ${name}: Map<string, string> = new Map<string, string>([\n` +
    Object.entries(entries).sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0)
      .map(([key, value]) => `  [${JSON.stringify(key)}, ${JSON.stringify(value)}]`).join(',\n') + '\n])\n';
}
const generated = '// Generated by tools/vendor-material-icons.cjs from material-icon-theme@5.38.1 (MIT).\n' +
  '// Source and license: resources/rawfile/file-icons/material/{SOURCE.json,LICENSE.txt}.\n' +
  '// Do not edit by hand; keep SVG assets and associations from the same pinned package.\n\n' +
  table('MATERIAL_FILE_NAMES', names) + '\n' + table('MATERIAL_FILE_EXTENSIONS', extensions) + '\n' +
  table('MATERIAL_LIGHT_ICONS', variants) + '\n' +
  `export const MATERIAL_FILE_NAME_MAX_DEPTH: number = ${Math.max(...Object.keys(names).map(name => name.split('/').length))}\n`;
fs.writeFileSync(path.join(root, 'entry/src/main/ets/config/MaterialFileIcons.ets'), generated);
console.log(`${used.size} SVGs, ${totalBytes} bytes, ${Object.keys(names).length} filenames, ${Object.keys(extensions).length} extensions.`);
